export function language(explicit, env = process.env, locale = Intl.DateTimeFormat().resolvedOptions().locale) {
  return explicit ?? (/^pt(?:[_-]|$)/i.test(env.LC_ALL || env.LC_MESSAGES || env.LANG || locale) ? 'pt-BR' : 'en');
}

export function messages(lang) { return lang === 'pt-BR' ? pt : en; }

// Only controlled messages reach the terminal; native errors can contain secrets.
export function safeError(error, lang) {
  const dictionary = messages(lang);
  return dictionary[error?.key] ?? dictionary.internal;
}
